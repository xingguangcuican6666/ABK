#!/usr/bin/env python3
"""Generate Compose vectors from the same normalized SVGs used by the web catalog."""
import json
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "abk-ui/src/main/kotlin/io/github/xingguangcuican6666/abk/ui/icons/AbkIcons.kt"


def geometry(node):
    tag = node.tag.rsplit("}", 1)[-1]
    a = node.attrib
    number = lambda name, default=0: float(a.get(name, default))
    if tag == "path":
        return a["d"]
    if tag == "line":
        return f'M{number("x1")} {number("y1")}L{number("x2")} {number("y2")}'
    if tag in ("polyline", "polygon"):
        values = re.findall(r"[-+]?(?:\d*\.)?\d+(?:[eE][-+]?\d+)?", a["points"])
        return "M" + " L".join(" ".join(values[i:i+2]) for i in range(0, len(values), 2)) + ("Z" if tag == "polygon" else "")
    if tag in ("circle", "ellipse"):
        x, y = number("cx"), number("cy")
        rx = number("r") if tag == "circle" else number("rx")
        ry = number("r") if tag == "circle" else number("ry")
        return f"M{x-rx} {y}a{rx} {ry} 0 1 0 {2*rx} 0a{rx} {ry} 0 1 0 {-2*rx} 0Z"
    if tag == "rect":
        x, y, w, h = (number(k) for k in ("x", "y", "width", "height"))
        rx, ry = min(number("rx", number("ry")), w/2), min(number("ry", number("rx")), h/2)
        if not rx or not ry:
            return f"M{x} {y}h{w}v{h}h{-w}Z"
        return (f"M{x+rx} {y}h{w-2*rx}a{rx} {ry} 0 0 1 {rx} {ry}v{h-2*ry}"
                f"a{rx} {ry} 0 0 1 {-rx} {ry}h{-w+2*rx}a{rx} {ry} 0 0 1 {-rx} {-ry}"
                f"v{-h+2*ry}a{rx} {ry} 0 0 1 {rx} {-ry}Z")
    raise ValueError(f"Unsupported geometry: {tag}")


def main():
    code = "const fs=require('fs'),vm=require('vm');let c={window:{}};vm.runInNewContext(fs.readFileSync(process.argv[1],'utf8'),c);console.log(JSON.stringify(c.window.ABKIconData));"
    data = json.loads(subprocess.check_output(["node", "-e", code, str(ROOT / "assets/vendor/icons/icon-data.js")]))
    icons = data["libraries"]["lucide"]["icons"]
    if set(data["roles"]) != set(icons):
        raise ValueError("Incomplete Lucide role coverage")
    lines = ["// Generated by scripts/generate-compose-icons.py. Do not edit geometry by hand.",
             "// Lucide ISC / Feather MIT: assets/abk/licenses/LICENSE-lucide.",
             "package io.github.xingguangcuican6666.abk.ui.icons", "",
             "import androidx.compose.ui.graphics.Color", "import androidx.compose.ui.graphics.SolidColor",
             "import androidx.compose.ui.graphics.StrokeCap", "import androidx.compose.ui.graphics.StrokeJoin",
             "import androidx.compose.ui.graphics.vector.ImageVector", "import androidx.compose.ui.graphics.vector.addPathNodes",
             "import androidx.compose.ui.unit.dp", "", "public object AbkIcons {"]
    names = []
    for role, svg in icons.items():
        name = "".join(word.capitalize() for word in role.split("-"))
        names.append((role, name))
        root = ET.fromstring(svg)
        view = [float(v) for v in root.attrib["viewBox"].split()]
        if view != [0, 0, 24, 24]:
            raise ValueError(f"Unsupported viewport for {role}")
        mirrored = str(role in ("back", "forward", "arrow-right")).lower()
        lines.extend([f"    public val {name}: ImageVector by lazy {{", f'        ImageVector.Builder("Abk.{name}", 24.dp, 24.dp, 24f, 24f, autoMirror = {mirrored}).apply {{'])
        for node in root:
            if "transform" in node.attrib:
                raise ValueError("Transformed SVG needs explicit support")
            attrs = {**root.attrib, **node.attrib}
            if attrs.get("fill") != "none" or attrs.get("stroke") != "currentColor":
                raise ValueError("Unexpected Lucide paint")
            path = geometry(node)
            width = float(attrs["stroke-width"])
            lines.extend(["            addPath(", f"                pathData = addPathNodes({json.dumps(path)}),",
                          "                fill = null, stroke = SolidColor(Color.Black),",
                          f"                strokeLineWidth = {width}f, strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round,",
                          "            )"])
        lines.extend(["        }.build()", "    }", ""])
    lines.append("    public val all: Map<String, ImageVector> by lazy {")
    lines.append("        linkedMapOf(")
    lines.extend(f'            "{role}" to {name},' for role, name in names)
    lines.extend(["        )", "    }", "}", ""])
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(lines))
    print(f"Generated {len(icons)} Compose vectors")


if __name__ == "__main__":
    main()
